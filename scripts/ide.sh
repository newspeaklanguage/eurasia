# The Newspeak IDE and the document viewer on Eurasia (M6 step 6): builds both
# from source with the build (scripts/build.sh ide viewer:
# newspeak/EurasiaBuild.ns generates each one's entry and finds its modules,
# the packager packages them, genesis makes their images, stamped by
# BuildInfo), and stages the images, the pages (web/ide.html, web/viewer.html),
# the VM, the libraries (web/libs) and the images in target/web, to
# be served and opened as ide.html and viewer.html?docName=<document>.
#
# Both are built a second time on the Croquet platform (croquet-ide,
# croquet-viewer: newspeak/platform/Eurasia/CroquetRuntime.ns), staged as
# ide/croquet.eus and viewer/croquet.eus for web/croquet.html, with Croquet's
# client (newspeak/out/croquet.min.js) and the Croquet support script
# (croquet-glue.js, generated by newspeak/tool/mirror-croquet-glue.py).
#
# It also stages them in the newspeak checkout's out/, beside psoup's
# primordialsoup.html, so that the server that serves out/ (localhost:8080)
# serves Eurasia too: eurasia-ide.html (image ide/base.eus),
# eurasia-viewer.html?docName=<document> (image viewer/base.eus) and
# eurasia-croquet.html?app=viewer|ide&... (see web/croquet.html), with the VM
# (eurasia.mjs, eurasia_web.wasm) and custom-post.js; the libraries and icons
# these pages load are out/'s own. Set EURASIA_NO_OUT=1 to skip it.
#
# Needs what scripts/build.sh needs (BUILDING.md), and newspeak/out/croquet.min.js
# for the Croquet pages.
set -eu
cd "$(dirname "$0")/.."
EURASIA=$(pwd)
NEWSPEAK=${NEWSPEAK:-$EURASIA/../newspeak}
PRIMORDIALSOUP=${PRIMORDIALSOUP:-$EURASIA/../primordialsoup}
OUT=$EURASIA/target/ide
WEB=$EURASIA/target/web
mkdir -p "$OUT" "$WEB/ide" "$WEB/viewer" "$WEB/vendor"

echo "== the IDE and the viewer, built from source, also on Croquet (scripts/build.sh ide viewer croquet-ide croquet-viewer)"
scripts/build.sh ide viewer croquet-ide croquet-viewer
cp target/build/ide/base.eus target/build/ide.entry.ns target/build/ide.modules.txt "$OUT/"
ls -l "$OUT/base.eus" target/build/viewer/base.eus
echo "== staging for a browser"
cp "$OUT/base.eus" "$WEB/ide/"
cp target/build/viewer/base.eus "$WEB/viewer/"
cp target/build/croquet-ide/base.eus "$WEB/ide/croquet.eus"
cp target/build/croquet-viewer/base.eus "$WEB/viewer/croquet.eus"
# The Croquet support script: the JS deploy's copy of the canonical glue.
python3 "$NEWSPEAK/tool/mirror-croquet-glue.py" --check --emit "$WEB/croquet-glue.js" ||
  echo "WARNING: DeploymentManager.ns's copy of the Croquet glue is stale (newspeak/tool/mirror-croquet-glue.py)"
cp "$NEWSPEAK/out/croquet.min.js" web/croquet.html web/croquet-boot.js "$WEB/"
cp web/ide.html web/viewer.html web/app.html web/eurasia.mjs web/images.mjs target/wasm32-unknown-unknown/release/eurasia_web.wasm "$WEB/"
# psoup's page helpers (safeDownloadBlob), canonical in primordialsoup.
cp "$PRIMORDIALSOUP/meta/custom-post.js" "$WEB/"
# The boot the viewer page uses, canonical in newspeak.
cp "$NEWSPEAK/deploy-boot.js" "$WEB/"
# The libraries (web/libs, laid out as served) and the images, all tracked.
# Everything in web/libs but its README, which must not land on (or replace)
# a README of the target's own.
(cd web/libs && find . -type f ! -name README.md | while read -r f; do
  mkdir -p "$WEB/$(dirname "$f")" && cp "$f" "$WEB/$f"
done)
cp "$NEWSPEAK"/*.png "$WEB/"
echo "IDE: serve $WEB and open ide.html; documents: viewer.html?docName=<document>."

if [ "${EURASIA_NO_OUT:-}" != 1 ]; then
  echo "== staging in $NEWSPEAK/out"
  NSOUT=$NEWSPEAK/out
  mkdir -p "$NSOUT/ide" "$NSOUT/viewer"
  cp "$OUT/base.eus" "$NSOUT/ide/"
  cp target/build/viewer/base.eus "$NSOUT/viewer/"
  cp "$WEB/ide/croquet.eus" "$NSOUT/ide/"
  cp "$WEB/viewer/croquet.eus" "$NSOUT/viewer/"
  cp "$WEB/croquet-glue.js" web/croquet-boot.js "$NSOUT/"
  cp web/croquet.html "$NSOUT/eurasia-croquet.html"
  cp web/eurasia.mjs web/images.mjs target/wasm32-unknown-unknown/release/eurasia_web.wasm "$PRIMORDIALSOUP/meta/custom-post.js" "$NSOUT/"
  cp web/ide.html "$NSOUT/eurasia-ide.html"
  cp web/viewer.html "$NSOUT/eurasia-viewer.html"
  cp "$NEWSPEAK/deploy-boot.js" "$NSOUT/"
  echo "Served from out/: eurasia-ide.html, eurasia-viewer.html?docName=<document>, eurasia-croquet.html?app=viewer|ide&...."
fi
