"""Build a Eurasia image of one of psoup's command-line applications (the
parser, the pretty-printer, the round-trip check, the test runner...), to run
on the command line under Node:

  scripts/tool-image.py TOOL.ns [MODULE.ns ...] OUTDIR
  node web/run-node.mjs target/web/eurasia_web.wasm OUTDIR/base.eus ARGS...
  (EURASIA_JIT=1 to compile methods)

TOOL.ns is a psoup application, `packageUsing: manifest`, with `main:args:`;
MODULEs are the modules it takes from its manifest. The generated entry
(OUTDIR/EurasiaTool.ns) has a slot for each, gives the tool a manifest
answering each by name, and builds Eurasia's base platform with mirrors
(RuntimeWithMirrors). The tool's own psoup file primitives become Eurasia's
natives (EurasiaPackager's psoupPrimitiveNatives), which run-node.mjs serves
from this machine's files.
"""

import os
import re
import subprocess
import sys

EURASIA = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NEWSPEAK = os.environ.get("NEWSPEAK", os.path.join(EURASIA, "..", "newspeak"))
PRIMORDIALSOUP = os.environ.get("PRIMORDIALSOUP", os.path.join(EURASIA, "..", "primordialsoup"))
PSOUP = os.path.join(PRIMORDIALSOUP, "out", "ReleaseX64", "primordialsoup")
P = os.path.join(PRIMORDIALSOUP, "newspeak")
E = os.path.join(NEWSPEAK, "platform", "Eurasia")

# The platform's modules (as scripts/reflection-tests.sh packages them): slot
# name, file.
PLATFORM = [
    ("Kernel", os.path.join(P, "Kernel.ns")),
    ("PrimordialSoupCollections", os.path.join(P, "platform", "PrimordialSoup", "Collections.ns")),
    ("Actors", os.path.join(E, "Actors.ns")),
    ("Runtime", os.path.join(E, "Runtime.ns")),
    ("Mirrors", os.path.join(E, "Mirrors.ns")),
    ("RuntimeWithMirrors", os.path.join(E, "RuntimeWithMirrors.ns")),
    ("NewspeakASTs", os.path.join(P, "NewspeakASTs.ns")),
    ("NewspeakPredictiveParsing", os.path.join(P, "NewspeakPredictiveParsing.ns")),
    ("IntermediatesForPrimordialSoup", os.path.join(P, "IntermediatesForPrimordialSoup.ns")),
    ("NewspeakCompilation", os.path.join(P, "NewspeakCompilation.ns")),
    ("NewspeakBytecodeCompilation", os.path.join(P, "NewspeakBytecodeCompilation.ns")),
    ("Newspeak2V5BytecodeCompilation", os.path.join(NEWSPEAK, "Newspeak2V5BytecodeCompilation.ns")),
    ("MetadataParsing", os.path.join(P, "MetadataParsing.ns")),
]


def class_name(path):
    with open(path, encoding="utf-8") as f:
        m = re.search(r"\bclass\s+([A-Za-z_][A-Za-z0-9_]*)", f.read())
    if not m:
        sys.exit(f"no class in {path}")
    return m.group(1)


def entry_source(tool, modules):
    names = [n for n, _ in PLATFORM] + [class_name(m) for m in modules] + [tool]
    answered = [n for n, _ in PLATFORM if n != "Kernel"] + [class_name(m) for m in modules]
    manifest = "\n".join(f"\t\tpublic {n} = ( ^outer EurasiaTool {n} )" for n in answered)
    slots = "\n".join(f"\t\t{n}" for n in names)
    return f"""Newspeak3
'Eurasia'
class EurasiaTool usingPlatform: platform = (
	(* {tool} (a psoup command-line application) on Eurasia: generated by eurasia/scripts/tool-image.py. *)
	|
{slots}
	|
) (
	class Manifest = () (
{manifest}
	) : ()
	public main: platform args: args = (
		^({tool} packageUsing: Manifest new) main: platform args: args
	)
	public platformOver: internalKernel = (
		| base |
		base:: (Runtime kernel: Kernel
			collections: PrimordialSoupCollections
			actors: Actors) Platform internalKernel: internalKernel.
		^(RuntimeWithMirrors mirrors: Mirrors
			asts: NewspeakASTs
			parsing: NewspeakPredictiveParsing
			intermediates: IntermediatesForPrimordialSoup
			compilation: (Newspeak2V5BytecodeCompilation mixinApply: (NewspeakBytecodeCompilation mixinApply: NewspeakCompilation))
			metadataParsing: MetadataParsing) Platform over: base
			internalKernel: internalKernel
	)
) : ()
"""


def packager(out):
    """EurasiaPackager.vfuel, rebuilt when EurasiaPackager.ns is newer."""
    vfuel = os.path.join(out, "EurasiaPackager.vfuel")
    source = os.path.join(NEWSPEAK, "EurasiaPackager.ns")
    if os.path.exists(vfuel) and os.path.getmtime(vfuel) >= os.path.getmtime(source):
        return vfuel
    sources = [os.path.join(".", "newspeak", f) for f in sorted(os.listdir(P)) if f.endswith(".ns")]
    platform_dir = os.path.join(P, "platform", "PrimordialSoup")
    sources += [os.path.join(".", "newspeak", "platform", "PrimordialSoup", f)
                for f in sorted(os.listdir(platform_dir)) if f.endswith(".ns")]
    log = os.path.join(out, "packager-build.log")
    with open(log, "w") as f:
        r = subprocess.run([PSOUP, "./out/snapshots/WebCompiler.vfuel", *sources,
                            os.path.join(NEWSPEAK, "Newspeak2V5BytecodeCompilation.ns"), source,
                            "PrimordialSoup/RuntimeWithMirrors", "EurasiaPackager", vfuel],
                           cwd=PRIMORDIALSOUP, stdout=f, stderr=subprocess.STDOUT)
    if r.returncode != 0 or not os.path.exists(vfuel):
        sys.exit(f"building the packager failed; see {log}")
    return vfuel


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    tool_path, *module_paths, out = [os.path.abspath(a) for a in sys.argv[1:]]
    os.makedirs(out, exist_ok=True)
    tool = class_name(tool_path)
    entry = os.path.join(out, "EurasiaTool.ns")
    with open(entry, "w", encoding="utf-8") as f:
        f.write(entry_source(tool, module_paths))
    log = os.path.join(out, "package.log")
    with open(log, "w") as f:
        subprocess.run([PSOUP, packager(out), os.path.join(E, "InternalKernel.ns"),
                        os.path.join(EURASIA, "kernel", "natives.tsv"), entry,
                        *[p for _, p in PLATFORM], *module_paths, tool_path,
                        os.path.join(out, "genesis.eus")], stdout=f, stderr=subprocess.STDOUT)
    with open(log) as f:
        if not any(line.startswith("Wrote") for line in f):
            sys.exit(f"packaging {tool} failed; see {log}")
    subprocess.run(["cargo", "build", "-q", "--release", "-p", "eurasia-native"], cwd=EURASIA, check=True)
    subprocess.run([os.path.join(EURASIA, "target", "release", "eurasia"), "genesis.eus", "base.eus"],
                   cwd=out, check=True)
    print(f"{tool}: {os.path.join(out, 'base.eus')}")


if __name__ == "__main__":
    main()
