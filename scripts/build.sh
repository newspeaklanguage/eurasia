# Builds the applications of the build list (newspeak/EurasiaBuildList.ns) from
# source, on Eurasia (EURASIA_BUILD_AND_DEPLOY_DESIGN_2026-11-21.md, section
# 3): EurasiaBuild packages them all with one packager, sharing the compiled
# modules, and genesis then makes each one's base image, in
# target/build/<name>/base.eus.
#
#   scripts/build.sh [NAME ...]     (only the named applications)
#
# Until stage 0 (design section 3.3), EurasiaBuild's own image is made by
# scripts/tool-image.py, which needs psoup.
set -eu
cd "$(dirname "$0")/.."
EURASIA=$(pwd)
NEWSPEAK=$(cd "${NEWSPEAK:-$EURASIA/../newspeak}" && pwd)
PRIMORDIALSOUP=$(cd "${PRIMORDIALSOUP:-$EURASIA/../primordialsoup}" && pwd)
OUT=$EURASIA/target/build
STAGE=$EURASIA/target/build-stage
WASM=$EURASIA/target/wasm32-unknown-unknown/release/eurasia_web.wasm
mkdir -p "$OUT"

echo "== the VM"
cargo build -q --release -p eurasia-native
cargo build -q --release -p eurasia-web --target wasm32-unknown-unknown

echo "== EurasiaBuild's image"
python3 scripts/tool-image.py "$NEWSPEAK/EurasiaBuild.ns" "$NEWSPEAK/platform/Eurasia/EurasiaPackager.ns" "$NEWSPEAK/platform/Eurasia/EurasiaNatives.ns" "$NEWSPEAK/EurasiaDeployment.ns" "$STAGE" > /dev/null

echo "== stamping BuildInfo"
NS_SHA=$(git -C "$NEWSPEAK" rev-parse --short HEAD 2>/dev/null || echo unknown)
NS_DATE=$(git -C "$NEWSPEAK" show -s --format=%cs HEAD 2>/dev/null || echo unknown)
VM_SHA=$(git -C "$EURASIA" rev-parse --short HEAD 2>/dev/null || echo unknown)
DIRTY=''
test -n "$(git -C "$NEWSPEAK" status --porcelain --untracked-files=no 2>/dev/null)$(git -C "$EURASIA" status --porcelain --untracked-files=no 2>/dev/null)" && DIRTY=' (dirty)'
BUILT=$(date -u +%Y-%m-%dT%H:%MZ)
cat > "$OUT/BuildInfo.ns" <<NSEOF
Newspeak3
'Root'
class BuildInfo packageUsing: manifest = (
	(* Build stamp -- GENERATED by eurasia/scripts/build.sh for this build; not tracked. *)
) (
) : (
	public builtAt = (
		^'${BUILT}'
	)
	public dirty = (
		^'${DIRTY}'
	)
	public version = (
		^'${NS_SHA} ${NS_DATE}, VM Eurasia ${VM_SHA}'
	)
)
NSEOF

echo "== packaging"
rm -f "$OUT"/*.genesis.eus
EURASIA_JIT=1 node web/run-node.mjs "$WASM" "$STAGE/base.eus" \
  "$NEWSPEAK" "$PRIMORDIALSOUP" "$EURASIA" "$OUT/BuildInfo.ns" "$OUT" "$@" | tee "$OUT/build.log"
ls "$OUT"/*.genesis.eus > /dev/null 2>&1 || { echo "nothing was packaged; see $OUT/build.log"; exit 1; }

echo "== genesis"
for g in "$OUT"/*.genesis.eus; do
  name=$(basename "$g" .genesis.eus)
  mkdir -p "$OUT/$name"
  (cd "$OUT/$name" && "$EURASIA/target/release/eurasia" "$g" base.eus)
  echo "$name: $OUT/$name/base.eus"
done
