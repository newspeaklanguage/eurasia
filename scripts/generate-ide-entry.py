"""Generate newspeak/EurasiaIDE.ns, the genesis entry of the Newspeak IDE on
Eurasia (M6 step 6), from the IDE's own manifest references.

HopscotchWebIDE is a psoup application: `packageUsing: manifest` takes its
modules (and its image resources) from a manifest by name. The genesis
packager instead fills an application's slots with the modules it packages.
The generated entry has a slot for every module the IDE names, and gives the
IDE a manifest answering each module by name and each image resource as the
file name the page serves. Its platform is Eurasia's base platform with
mirrors (RuntimeWithMirrors) and Hopscotch (WebRuntime).

Usage: generate-ide-entry.py <newspeak checkout> <primordialsoup checkout>
<output>. It also prints the module files to package, one per line, after
`MODULES:`.
"""

import os
import re
import sys

# The platform's own modules, packaged before the IDE's: N the newspeak
# checkout, P psoup's newspeak directory, E Eurasia's platform directory
# (newspeak/platform/Eurasia, PLATFORM_NAMESPACES_DESIGN_2026-11-18.md).
PLATFORM = [
    ("P", "Kernel"), ("P", "CollectionsForPrimordialSoup"), ("E", "Actors"),
    ("E", "Runtime"), ("E", "Mirrors"), ("E", "RuntimeWithMirrors"),
    ("E", "WebRuntime"), ("N", "Ducts"), ("N", "GraphicsForHTML5"),
    ("N", "FontsForHTML5"), ("N", "TextModule"), ("N", "HopscotchForHTML5"),
    ("N", "VoiceController"), ("N", "AIAccess"), ("P", "NewspeakASTs"),
    ("P", "NewspeakPredictiveParsing"), ("P", "IntermediatesForPrimordialSoup"),
    ("P", "NewspeakCompilation"), ("P", "NewspeakBytecodeCompilation"),
    ("N", "Newspeak2V5BytecodeCompilation"), ("P", "MetadataParsing"),
    ("N", "HopscotchWebIDE"),
]


def main():
    newspeak, psoup, output = sys.argv[1:4]
    ide = open(os.path.join(newspeak, "HopscotchWebIDE.ns")).read()
    # Another platform's modules, manifest P X (PLATFORM_NAMESPACES_DESIGN_2026-11-18.md):
    # packaged from newspeak/platform/P, they fill the slots named PX.
    platforms = {}
    for p, n in re.findall(r"manifest ([A-Za-z_0-9]+) ([A-Za-z_0-9]+)", ide):
        if os.path.exists(os.path.join(newspeak, "platform", p, n + ".ns")):
            platforms.setdefault(p, set()).add(n)
    # Comments mention words after 'manifest' too; keep names that are files.
    names = sorted(set(re.findall(r"manifest ([A-Za-z_0-9]+)", ide)) - set(platforms))
    modules, images = [], []
    for n in names:
        if os.path.exists(os.path.join(newspeak, n + ".ns")):
            modules.append(("N", n))
        elif os.path.exists(os.path.join(psoup, "newspeak", n + ".ns")):
            modules.append(("P", n))
        elif os.path.exists(os.path.join(newspeak, n + ".png")) or os.path.exists(
                os.path.join(newspeak, "out", n + ".png")):
            images.append(n)
    seen = set()
    all_modules = []
    for where, n in PLATFORM + modules:
        if n not in seen:
            seen.add(n)
            all_modules.append((where, n))
    foreign = [(p, n) for p in sorted(platforms) for n in sorted(platforms[p])]
    slots = "\n".join([f"\t\t{n}" for _, n in all_modules] + [f"\t\t{p}{n}" for p, n in foreign])
    lookups = "\n".join([f"\t\t\t'{n}' = name ifTrue: [ ^outer EurasiaIDE {n} ]." for _, n in modules]
                        + [f"\t\t\t'{p}' = name ifTrue: [ ^PlatformManifest named: '{p}' ]." for p in sorted(platforms)])
    platform_lookups = "\n".join(f"\t\t\t('{p}' = platform and: [ '{n}' = name ]) ifTrue: [ ^outer EurasiaIDE {p}{n} ]."
                                  for p, n in foreign)
    image_checks = " ".join(f"'{n}'." for n in images)
    src = f"""Newspeak3
'Eurasia'
class EurasiaIDE usingPlatform: platform = (
	(* The Newspeak IDE (HopscotchWebIDE) on Eurasia's web host: generated by eurasia/scripts/generate-ide-entry.py from the IDE's manifest references. The genesis packager packages it as if nested in InternalKernel and fills the module slots below. Genesis builds the platform (platformOver:): Eurasia's base platform with mirrors and Hopscotch. In a browser, main:args: starts the IDE with a manifest answering its modules by name, and its image resources as the files the page serves. *)

	|
{slots}
		internalKernel
	|
) (
	class Manifest new = (
		(* The IDE's manifest: its modules by name, and its image resources as file names. *)

	) (
		doesNotUnderstand: message = (
			| name = message selector. |
{lookups}
			({{{image_checks} }} includes: name) ifTrue: [ ^name , '.png' ].
			^super doesNotUnderstand: message
		)
	) : ()
	class PlatformManifest named: p = (
		(* Another platform's modules, manifest P X: the slot named PX. *)

		|
			platform = p.
		|
	) (
		doesNotUnderstand: message = (
			| name = message selector. |
{platform_lookups}
			^super doesNotUnderstand: message
		)
	) : ()
	public main: platform args: args = (
		(HopscotchWebIDE packageUsing: Manifest new) main: platform args: args
	)
	public platformOver: ik = (
		| base reflective |
		internalKernel:: ik.
		base:: (Runtime kernel: Kernel
			collections: CollectionsForPrimordialSoup
			actors: Actors) Platform internalKernel: ik.
		reflective:: (RuntimeWithMirrors mirrors: Mirrors
			asts: NewspeakASTs
			parsing: NewspeakPredictiveParsing
			intermediates: IntermediatesForPrimordialSoup
			compilation: (Newspeak2V5BytecodeCompilation mixinApply: (NewspeakBytecodeCompilation mixinApply: NewspeakCompilation))
			metadataParsing: MetadataParsing) Platform over: base internalKernel: ik.
		^((WebRuntime internalKernel: (reflective mirrors ObjectMirror reflecting: ik) getClass reflectee
			hopscotch: HopscotchForHTML5
			ducts: Ducts
			graphics: GraphicsForHTML5
			fonts: FontsForHTML5
			text: TextModule
			voiceController: VoiceController
			aiAccess: AIAccess) Platform over: reflective) buildInfo: BuildInfo;
			hostModule: Host;
			yourself
	)
) : ()
"""
    open(output, "w").write(src)
    print("MODULES:")
    for where, n in all_modules:
        directory = {"N": newspeak, "P": os.path.join(psoup, "newspeak"),
                     "E": os.path.join(newspeak, "platform", "Eurasia")}[where]
        print(os.path.join(directory, n + ".ns"))
    for p, n in foreign:
        print(os.path.join(newspeak, "platform", p, n + ".ns"))


main()
