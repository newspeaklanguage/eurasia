"""The natives catalog as a Newspeak module (EURASIA_BUILD_AND_DEPLOY_DESIGN_2026-11-21.md,
section 2.4): newspeak/platform/Eurasia/EurasiaNatives.ns, generated from
kernel/natives.tsv, so that packaging in Newspeak (EurasiaBuild, and the IDEs
later) takes the catalog as a module rather than reading a file.

  scripts/natives-module.py           writes the module, pretty-printed
  scripts/natives-module.py --check   fails when the module and the table differ

The table stays the source: natives_table.rs checks it against natives.rs.
"""

import os
import re
import subprocess
import sys
import tempfile

EURASIA = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NEWSPEAK = os.environ.get("NEWSPEAK", os.path.join(EURASIA, "..", "newspeak"))
TABLE = os.path.join(EURASIA, "kernel", "natives.tsv")
MODULE = os.path.join(NEWSPEAK, "platform", "Eurasia", "EurasiaNatives.ns")


def rows():
    result = []
    with open(TABLE, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            cls, side, selector, name, number = line.split("\t")
            result.append((cls, side, selector, name, int(number)))
    return result


def quoted(s):
    return "'" + s.replace("'", "''") + "'"


def source():
    entries = " ".join(
        "{" + ". ".join([quoted(c), quoted(side), quoted(sel), quoted(name), str(n)]) + ". }."
        for c, side, sel, name, n in rows())
    return f"""Newspeak3
'Eurasia'
class EurasiaNatives = (
	(* The kernel's natives catalog, as the genesis packager uses it: kernel class, side (instance or class), selector, native name, native id. GENERATED by eurasia/scripts/natives-module.py from eurasia/kernel/natives.tsv, which is the source (checked against eurasia-core's natives.rs); do not edit. The ids belong to one kernel version (eurasia-core's version.rs). *)
) (
	public table ^<Array[{{String. String. String. String. Integer}}]> = (
		^{{{entries} }}
	)
) : ()
"""


def module_rows():
    with open(MODULE, encoding="utf-8") as f:
        text = f.read()
    found = re.findall(r"\{'((?:[^']|'')*)'\.\s*'((?:[^']|'')*)'\.\s*'((?:[^']|'')*)'\.\s*'((?:[^']|'')*)'\.\s*(\d+)\.\s*\}", text)
    return [(c.replace("''", "'"), s.replace("''", "'"), sel.replace("''", "'"), name.replace("''", "'"), int(n))
            for c, s, sel, name, n in found]


def main():
    if sys.argv[1:] == ["--check"]:
        if not os.path.exists(MODULE) or module_rows() != rows():
            sys.exit(f"{MODULE} does not match {TABLE}: run scripts/natives-module.py")
        print(f"EurasiaNatives.ns matches natives.tsv ({len(rows())} natives)")
        return
    tool = os.path.join(NEWSPEAK, "tool")
    with tempfile.NamedTemporaryFile("w", suffix=".ns", delete=False, encoding="utf-8") as f:
        f.write(source())
        raw = f.name
    try:
        subprocess.run(["./pretty-print.sh", raw, MODULE], cwd=tool, check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    finally:
        os.unlink(raw)
    if module_rows() != rows():
        sys.exit("the pretty-printed module does not hold the table")
    print(f"{MODULE}: {len(rows())} natives")


if __name__ == "__main__":
    main()
